"""One release identity for firmware and GUI; no dependencies or credentials.

Changed source automatically advances the patch number. Identical rebuilds and
reflashes retain it, so firmware and GUI built separately still match.
"""
import argparse
from contextlib import contextmanager
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
GENERATED = {"firmware/main/sw_version.h", "frontend/src/sw_version.ts"}


def source_files(root):
    files = []
    for folder in ("firmware/main", "frontend/src", "backend/app", "scripts"):
        files.extend(p for p in (root / folder).rglob("*") if p.is_file()
                     and p.suffix in {".c", ".h", ".py", ".ts", ".tsx", ".css", ".json",
                                      ".ps1", ".cmake", ".txt", ".yml", ".mjs"}
                     and "__pycache__" not in p.parts)
    for name in ("CMakeLists.txt", "firmware/CMakeLists.txt", "sdkconfig.defaults",
                 "firmware/sdkconfig.defaults", "firmware/partitions.csv",
                 "frontend/package.json", "frontend/package-lock.json",
                 "frontend/vite.config.ts", "frontend/tsconfig.json", "backend/requirements.txt"):
        if (root / name).is_file():
            files.append(root / name)
    return sorted({p for p in files if p.relative_to(root).as_posix() not in GENERATED
                   and "/test/" not in p.relative_to(root).as_posix()},
                  key=lambda p: p.relative_to(root).as_posix())


def fingerprint(root):
    digest = hashlib.sha256()
    for path in source_files(root):
        digest.update(path.relative_to(root).as_posix().encode() + b"\0")
        digest.update(path.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return digest.hexdigest()


def write_changed(path, text):
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


@contextmanager
def version_lock(root):
    lock = root / ".runtime" / "version.lock"
    lock.parent.mkdir(exist_ok=True)
    with lock.open("a+b") as stream:
        stream.seek(0)
        if not stream.read(1):
            stream.write(b"0")
            stream.flush()
        stream.seek(0)
        if os.name == "nt":
            import msvcrt
            for attempt in range(100):
                try:
                    msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, 1)
                    break
                except OSError:
                    if attempt == 99:
                        raise
                    time.sleep(.05)
        else:
            import fcntl
            fcntl.flock(stream.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            stream.seek(0)
            if os.name == "nt":
                msvcrt.locking(stream.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(stream.fileno(), fcntl.LOCK_UN)


def sync(root=ROOT, bump=False, check=False):
    with version_lock(root):
        path = root / "version.json"
        info = json.loads(path.read_text(encoding="utf-8"))
        if not re.fullmatch(r"\d+\.\d+\.\d+", info["sw_version"]):
            raise ValueError("version.json sw_version must be major.minor.patch")
        current = fingerprint(root)
        changed = current != info.get("source_sha256")
        if check and changed:
            raise ValueError("Source changed since version preparation. Rebuild firmware and GUI.")
        if bump or changed:
            if bump or info.get("source_sha256"):
                major, minor, patch = map(int, info["sw_version"].split("."))
                info["sw_version"] = f"{major}.{minor}.{patch + 1}"
            info.update(source_sha256=current,
                        built_at_utc=datetime.now(timezone.utc).isoformat(timespec="seconds"))
        version, build, stamp = info["sw_version"], current[:12], info["built_at_utc"]
        header = ("/* Generated by scripts/sync_version.py; edit version.json, not this file. */\n"
                  f'#pragma once\n#define SW_VERSION "{version}"\n'
                  f'#define SW_BUILD_ID "{build}"\n#define SW_BUILD_UTC "{stamp}"\n')
        ts = ("// Generated by scripts/sync_version.py; edit version.json, not this file.\n"
              f'export const SW_VERSION = "{version}";\n'
              f'export const SW_BUILD_ID = "{build}";\nexport const SW_BUILD_UTC = "{stamp}";\n')
        outputs = {path: json.dumps(info, indent=2) + "\n",
                   root / "firmware/main/sw_version.h": header,
                   root / "frontend/src/sw_version.ts": ts}
        for destination, content in outputs.items():
            if check:
                if not destination.is_file() or destination.read_text(encoding="utf-8") != content:
                    raise ValueError(f"Version file is out of date: {destination.name}")
            else:
                write_changed(destination, content)
        return info


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bump", action="store_true", help="Force a new patch release")
    parser.add_argument("--check", action="store_true", help="Reject stale release inputs")
    args = parser.parse_args()
    if args.bump and args.check:
        parser.error("--bump and --check cannot be combined")
    result = sync(bump=args.bump, check=args.check)
    print(f"SW_VERSION={result['sw_version']} BUILD={result['source_sha256'][:12]}")
